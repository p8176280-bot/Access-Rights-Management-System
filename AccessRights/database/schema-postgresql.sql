-- =====================================================================
--  Access Rights Management System - PostgreSQL schema
--  รันด้วย:  psql -U access_app -h localhost -d access_rights -f schema-postgresql.sql
--  (รันซ้ำได้ ไม่ลบข้อมูลเดิม)
-- =====================================================================

-- ---------------------------------------------------------------------
-- Users และบทบาท (หนึ่งคนมีได้หลายบทบาท)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS users (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)   NOT NULL,
    full_name      VARCHAR(150)  NOT NULL,
    email          VARCHAR(150)  NOT NULL,
    password_hash  VARCHAR(500)  NOT NULL,
    is_active      BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email    UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id  INTEGER     NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role     VARCHAR(20) NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role),
    CONSTRAINT ck_user_roles_role CHECK (role IN ('Admin', 'Requester', 'Approver'))
);

-- ---------------------------------------------------------------------
-- Rights: รายการสิทธิที่ขอได้ (Admin กำหนดผู้อนุมัติประจำสิทธิ)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS rights (
    id                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(150)  NOT NULL,
    description        VARCHAR(1000),
    approver_id        INTEGER       NOT NULL REFERENCES users (id),
    max_duration_days  INTEGER,                       -- NULL = ไม่กำหนดวันหมดอายุ
    is_active          BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_rights_name UNIQUE (name),
    CONSTRAINT ck_rights_max_duration CHECK (max_duration_days IS NULL OR max_duration_days BETWEEN 1 AND 3650)
);

-- ---------------------------------------------------------------------
-- Access Requests: 1 คำขอ = 1 สิทธิ, ผู้อนุมัติ 1 คน (BR-07)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS access_requests (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id      INTEGER       NOT NULL REFERENCES users (id),
    right_id          INTEGER       NOT NULL REFERENCES rights (id),
    approver_id       INTEGER       NOT NULL REFERENCES users (id),
    reason            VARCHAR(1000) NOT NULL,
    end_date          DATE,                           -- ผู้ยื่นระบุ (ไม่เกิน max_duration_days ของสิทธิ)
    status            VARCHAR(20)   NOT NULL,
    decided_by_id     INTEGER       REFERENCES users (id),
    decided_at        TIMESTAMPTZ,
    decision_comment  VARCHAR(1000),
    created_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ,
    version           INTEGER       NOT NULL DEFAULT 0,  -- กันการแก้ไข/พิจารณาชนกัน
    CONSTRAINT ck_requests_status CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Cancelled')),
    -- BR-09: ปฏิเสธต้องมีเหตุผล
    CONSTRAINT ck_requests_reject_reason CHECK (
        status <> 'Rejected' OR (decision_comment IS NOT NULL AND length(btrim(decision_comment)) > 0)),
    -- BR-08: ห้ามพิจารณาคำขอของตนเอง
    CONSTRAINT ck_requests_not_self_decided CHECK (decided_by_id IS NULL OR decided_by_id <> requester_id)
);

-- BR-04: ผู้ใช้หนึ่งคนมีคำขอ Pending ของสิทธิเดียวกันได้ครั้งละ 1 รายการ
CREATE UNIQUE INDEX IF NOT EXISTS ux_access_requests_one_pending
    ON access_requests (requester_id, right_id) WHERE status = 'Pending';
CREATE INDEX IF NOT EXISTS ix_access_requests_requester ON access_requests (requester_id, status);
CREATE INDEX IF NOT EXISTS ix_access_requests_approver  ON access_requests (approver_id, status);

-- ---------------------------------------------------------------------
-- ประวัติการดำเนินการกับคำขอ (BR-10) - เพิ่มได้อย่างเดียว
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS request_histories (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    access_request_id  INTEGER       NOT NULL REFERENCES access_requests (id),
    action             VARCHAR(20)   NOT NULL,
    actor_id           INTEGER       NOT NULL REFERENCES users (id),
    comment            VARCHAR(1000),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT ck_histories_action CHECK (action IN ('Created', 'Edited', 'Cancelled', 'Approved', 'Rejected'))
);
CREATE INDEX IF NOT EXISTS ix_request_histories_request ON request_histories (access_request_id, created_at);

CREATE OR REPLACE FUNCTION fn_request_histories_readonly() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'request_histories เป็นข้อมูลประวัติ แก้ไขหรือลบไม่ได้ (BR-10)';
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_request_histories_readonly ON request_histories;
CREATE TRIGGER trg_request_histories_readonly
    BEFORE UPDATE OR DELETE ON request_histories
    FOR EACH ROW EXECUTE FUNCTION fn_request_histories_readonly();

-- ---------------------------------------------------------------------
-- การแจ้งเตือนภายในระบบ (BR-06)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     INTEGER       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    title       VARCHAR(200)  NOT NULL,
    message     VARCHAR(1000) NOT NULL,
    link        VARCHAR(300),
    is_read     BOOLEAN       NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_notifications_user ON notifications (user_id, is_read, created_at DESC);

-- ---------------------------------------------------------------------
-- Views สำหรับรายงาน / ตรวจสอบ
-- ---------------------------------------------------------------------
-- สิทธิที่ยังใช้งานอยู่ (อนุมัติแล้ว และยังไม่หมดอายุ)
CREATE OR REPLACE VIEW v_active_rights AS
SELECT r.id            AS request_id,
       u.username,
       u.full_name,
       rt.name         AS right_name,
       r.decided_at    AS approved_at,
       r.end_date
FROM access_requests r
JOIN users  u  ON u.id  = r.requester_id
JOIN rights rt ON rt.id = r.right_id
WHERE r.status = 'Approved'
  AND (r.end_date IS NULL OR r.end_date >= CURRENT_DATE);

-- ประวัติการพิจารณา (เฉพาะอนุมัติ / ปฏิเสธ)
CREATE OR REPLACE VIEW v_decision_log AS
SELECT h.created_at    AS decided_at,
       h.action,
       a.full_name     AS decided_by,
       u.full_name     AS requester,
       rt.name         AS right_name,
       h.comment,
       r.id            AS request_id
FROM request_histories h
JOIN access_requests r ON r.id  = h.access_request_id
JOIN users  a  ON a.id  = h.actor_id
JOIN users  u  ON u.id  = r.requester_id
JOIN rights rt ON rt.id = r.right_id
WHERE h.action IN ('Approved', 'Rejected');
